"""Tests for the Alembic migration chain (DBF-AC02, DBF-AC08).

Drives Alembic entirely through its public Python API
(``alembic.config.Config`` / ``alembic.command``) against the
database ``conftest.py``'s ``db_url`` fixture configures (a
temporary SQLite file by default, or PostgreSQL under
``--db-backend=postgresql``), and reads the result back with
SQLAlchemy (never ``sqlite3``/``psycopg`` directly, per DBF-R01).
That fixture also points ``INSPECTFLOW_DATABASE_URL`` at the same
database and disposes the shared engine before and after each test,
so a stale cached engine from an earlier test (or from this test's
own ``get_engine()`` calls) never leaks into another test or into
the real default database under ``backend/data``.
"""

from pathlib import Path

from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, inspect, text

from alembic import command

_BACKEND_DIR = Path(__file__).resolve().parents[2]
_ALEMBIC_INI = _BACKEND_DIR / "alembic.ini"


def _alembic_config() -> Config:
    return Config(str(_ALEMBIC_INI))


def _stamped_version(db_url: str) -> str | None:
    engine = create_engine(db_url)
    try:
        with engine.connect() as conn:
            return conn.execute(
                text("SELECT version_num FROM alembic_version")
            ).scalar()
    finally:
        engine.dispose()


def test_upgrade_head_creates_a_single_head_and_stamps_it(db_url):
    cfg = _alembic_config()

    command.upgrade(cfg, "head")

    script_dir = ScriptDirectory.from_config(cfg)
    heads = script_dir.get_heads()
    assert len(heads) == 1
    (expected_head,) = heads

    assert _stamped_version(db_url) == expected_head


def test_baseline_upgrade_creates_no_tables_besides_alembic_version(
    db_url,
):
    """Upgrades only to the chain's root (the baseline), not to
    ``head``, so this stays true after later migrations add tables.
    """
    cfg = _alembic_config()
    baseline = ScriptDirectory.from_config(cfg).get_base()
    assert baseline is not None

    command.upgrade(cfg, baseline)

    engine = create_engine(db_url)
    try:
        table_names = inspect(engine).get_table_names()
    finally:
        engine.dispose()
    assert table_names == ["alembic_version"]


def test_check_reports_metadata_in_sync_with_the_migrated_schema(db_url):
    """``alembic check`` compares ``Base.metadata`` (what env.py
    binds ``target_metadata`` to) against the migrated database and
    must find no drift -- proving env.py is wired to the
    application's real metadata rather than an empty stand-in, and
    guarding against a future model being added without a matching
    migration.
    """
    cfg = _alembic_config()
    command.upgrade(cfg, "head")

    command.check(cfg)  # raises AutogenerateDiffsDetected on drift


def test_downgrade_base_removes_the_version_stamp(db_url):
    cfg = _alembic_config()
    command.upgrade(cfg, "head")

    command.downgrade(cfg, "base")

    # Alembic keeps the bookkeeping table itself (it does not drop
    # it on downgrade), but clears its one row once no revision is
    # applied.
    assert _stamped_version(db_url) is None


def test_downgrade_base_then_upgrade_head_round_trip(db_url):
    """Downgrading to ``base`` and upgrading back to ``head`` from
    there succeeds -- proving the chain survives a downgrade/upgrade
    round trip, not only a single upgrade against a database that
    has never been touched before (DBF-AC08).
    """
    cfg = _alembic_config()
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert _stamped_version(db_url) is None

    command.upgrade(cfg, "head")

    expected_head = ScriptDirectory.from_config(cfg).get_current_head()
    assert _stamped_version(db_url) == expected_head


def test_upgrade_head_works_from_a_non_backend_working_directory(
    db_url, tmp_path, monkeypatch
):
    """env.py must not depend on the process's current working
    directory to import ``app`` or to locate the database: this
    test runs with ``tmp_path`` (not ``backend/``) as cwd, relying
    only on ``alembic.ini``'s own ``%(here)s``-based
    ``prepend_sys_path`` and on passing an absolute ``alembic.ini``
    path to ``Config``.
    """
    monkeypatch.chdir(tmp_path)
    cfg = _alembic_config()

    command.upgrade(cfg, "head")

    expected_head = ScriptDirectory.from_config(cfg).get_current_head()
    assert _stamped_version(db_url) == expected_head
